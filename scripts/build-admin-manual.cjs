  <div class="page-break">
    <h1>فصل نهم و دهم: معاملات، خزانه‌داری و چک‌های صیادی</h1>

    <h2>معاملات تجاری (Transactions):</h2>
    <ul>
      <li><b>فاکتور خرید (Purchase):</b> ثبت خرید نهاده، جوجه یا خدمات. در فاکتور خرید می‌توان مشخص کرد که کالا وارد کدام انبار شود، طرف‌حساب کیست، نحوه پرداخت (نقد، چک، نسیه) چیست و به کدام گله اختصاص دارد.</li>
      <li><b>فاکتور فروش (Sale):</b> ثبت فروش پرنده زنده پای باسکول، کود سالن، یا فرآورده‌های قطعه‌بندی‌شده همراه با قیمت فی، وزن باسکول، کسورات و مالیات بر ارزش افزوده در صورت نیاز.</li>
      <li><b>برگشت از خرید و برگشت از فروش:</b> مدیریت مرجوعی نهاده‌های نامرغوب یا عودت کالاها با اصلاح خودکار انبار و تراز مالی طرف‌حساب.</li>
    </ul>

    <h2>خزانه‌داری و چک‌های صیادی بنفش (Sayad Cheques):</h2>
    <p>
      با توجه به قانون جدید چک، چرخه حیات کامل چک صیادی ۱۶ رقمی با وضعیت‌های زیر پیاده‌سازی شده است:
    </p>
    <ul>
      <li><b>نزد صندوق (In Hand / Pending):</b> چک دریافت شده از خریدار که هنوز سررسید آن فرا نرسیده است.</li>
      <li><b>وصول‌شده (Cleared):</b> با فرارسیدن سررسید و پاس شدن، وجه مستقیماً به موجودی حساب بانک انتخابی اضافه می‌شود.</li>
      <li><b>واگذارشده به غیر (Passed On / خرج‌شده):</b> چک مشتری بدون نقد شدن، بابت بدهی به فروشنده دان یا جوجه واگذار می‌شود.</li>
      <li><b>برگشت‌خورده (Bounced):</b> در صورت عدم موجودی، برگشت زده شده و حساب طرف‌حساب مجدداً بدهکار ثبت می‌شود.</li>
    </ul>

    <h2>راس‌گیری زمانی موزون چک‌ها (Raas Calculation):</h2>
    <p>
      هنگامی که خریدار چندین فقره چک با مبالغ و تاریخ‌های مختلف بابت یک محموله گوشت ارائه می‌دهد، سیستم با فرمول میانگین موزون ریالی، <b>تاریخ راس دقیق (سررسید موثر یکجا)</b> و تعداد روز راس را محاسبه می‌کند:
    </p>
    <div class="formula-box">
      Average Days = ∑ (مبلغ هر چک × فاصله روز تا مبدا) / جمع کل مبالغ چک‌ها
    </div>
  </div>

