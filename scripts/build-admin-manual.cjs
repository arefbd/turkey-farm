  <div class="page-break">
    <h1>فصل ششم: ساختار مشارکت، تسهیم سود و تسویه‌حساب</h1>
    <p>
      یکی از قوی‌ترین ویژگی‌های نسخه جدید، مدیریت دقیق و چندلایه‌ای شراکت‌هاست. در مزارع بوقلمون معمول است که در یک گله سه نفر شریک باشند، اما در گله دیگر درصدها متفاوت بوده یا حتی شرکای دیگری حضور داشته باشند.
    </p>

    <h2>واحدهای مشارکت مستقل (Partnership Units):</h2>
    <ul>
      <li><b>شراکت عمومی فارم (General Farm):</b> درصد ثابتی از کل فعالیت‌ها، هزینه‌های ثابت و تجهیزات.</li>
      <li><b>شراکت اختصاصی یک گله (Flock-specific Share):</b> مثلاً در گله ۱: شریک الف ۵۰٪ و شریک ب ۵۰٪؛ اما در گله ۲: شریک الف ۳۰٪، شریک ب ۳۰٪ و شریک ج ۴۰٪ سهم دارند.</li>
      <li><b>شراکت در معامله بازرگانی (Trading Deal):</b> مشارکت روی خرید و انبارش یک پارت مشخص گوشت منجمد.</li>
    </ul>

    <h2>تسهیم ریالی درآمدها و هزینه‌ها:</h2>
    <p>
      سامانه برای هر گله، درآمدهای فروش و هزینه‌ها را تفکیک نموده و برای هر شریک موارد زیر را با دقت تا تک تومان محاسبه می‌کند:
    </p>
    <ul>
      <li><b>سهم از درآمد (Share of Revenue):</b> حاصل‌ضرب درصد سهم شریک در گله در کل فروش‌های همان گله.</li>
      <li><b>سهم از هزینه کل (Share of Total Expenses):</b> سهم شریک از هزینه‌های مستقیم گله و خریدهای مربوطه.</li>
      <li><b>سود/زیان خالص سهم شریک:</b> تفاضل سهم از درآمد منهای سهم از کل هزینه.</li>
      <li><b>مانده حساب نهایی شریک:</b> آورده نقدی + هزینه‌های پرداخت‌شده مستقیم از جیب - برداشت‌ها و سود قابل تسویه.</li>
    </ul>

    <h2>الگوریتم تسویه بهینه شرکا (Suggest Transfers):</h2>
    <p>
      در پایان دوره پرورشی، سیستم جدولی از حداقل تعداد انتقالات بین شرکا را پیشنهاد می‌دهد؛ مثلاً: <i>«شریک الف مبلغ ۱۲۰,۰۰۰,۰۰۰ تومان به شریک ب پرداخت کند تا مانده حساب تمام شرکا صفر و تسویه کامل شود.»</i>
    </p>
  </div>

